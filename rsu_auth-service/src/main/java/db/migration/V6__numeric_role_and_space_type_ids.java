package db.migration;

import java.sql.Connection;
import java.sql.DatabaseMetaData;
import java.sql.PreparedStatement;
import java.sql.ResultSet;
import java.sql.Statement;
import java.util.ArrayList;
import java.util.Comparator;
import java.util.HashMap;
import java.util.List;
import java.util.Map;

import org.flywaydb.core.api.migration.BaseJavaMigration;
import org.flywaydb.core.api.migration.Context;

/** Converts the H2/PostgreSQL UUID catalog keys without dropping catalog data or relations. */
public class V6__numeric_role_and_space_type_ids extends BaseJavaMigration {
    private static final Map<String, Long> STANDARD_ROLE_IDS = Map.of(
            "ADMINISTRATOR", 1L,
            "MANAGER", 2L,
            "USER", 3L,
            "VISITOR", 4L);

    private static final Map<String, Long> STANDARD_TYPE_IDS = Map.of(
            "10000000-0000-0000-0000-000000000001", 1L,
            "10000000-0000-0000-0000-000000000002", 2L,
            "10000000-0000-0000-0000-000000000003", 3L);

    @Override
    public void migrate(Context context) throws Exception {
        Connection connection = context.getConnection();
        Map<String, Long> roleIds = roleIds(connection);
        Map<String, Long> typeIds = typeIds(connection);
        List<Relation> userRoles = readRelations(connection, "usuario_roles", "usuario_id", "rol_id", roleIds);
        List<Relation> spaceTypes = readRelations(connection, "espacios", "id", "tipo_espacio_id", typeIds);

        dropForeignKeyForColumn(connection, "usuario_roles", "rol_id");
        dropForeignKeyForColumn(connection, "espacios", "tipo_espacio_id");
        dropPrimaryKey(connection, "roles");
        dropPrimaryKey(connection, "tipos_espacio");
        dropPrimaryKey(connection, "usuario_roles");

        execute(connection, "ALTER TABLE roles ADD COLUMN id_numeric BIGINT");
        execute(connection, "ALTER TABLE tipos_espacio ADD COLUMN id_numeric BIGINT GENERATED BY DEFAULT AS IDENTITY");
        execute(connection, "ALTER TABLE usuario_roles ADD COLUMN rol_id_numeric BIGINT");
        execute(connection, "ALTER TABLE espacios ADD COLUMN tipo_espacio_id_numeric BIGINT");

        updateIds(connection, "roles", "id_numeric", "id", roleIds);
        updateIds(connection, "tipos_espacio", "id_numeric", "id", typeIds);
        updateRelations(connection, "usuario_roles", "usuario_id", "rol_id", "rol_id_numeric", userRoles);
        updateRelations(connection, "espacios", "id", "tipo_espacio_id", "tipo_espacio_id_numeric", spaceTypes);

        replaceIdColumn(connection, "roles", "id", "id_numeric", "roles_numeric_pk");
        replaceIdColumn(connection, "tipos_espacio", "id", "id_numeric", "tipos_espacio_numeric_pk");
        replaceReferenceColumn(connection, "usuario_roles", "rol_id", "rol_id_numeric", "usuario_roles_numeric_pk");
        replaceReferenceColumn(connection, "espacios", "tipo_espacio_id", "tipo_espacio_id_numeric", null);

        long nextTypeId = typeIds.values().stream().mapToLong(Long::longValue).max().orElse(0L) + 1;
        execute(connection, "ALTER TABLE tipos_espacio ALTER COLUMN id RESTART WITH " + nextTypeId);
        execute(connection, "ALTER TABLE usuario_roles ADD CONSTRAINT usuario_roles_rol_fk "
                + "FOREIGN KEY (rol_id) REFERENCES roles(id)");
        execute(connection, "ALTER TABLE espacios ADD CONSTRAINT espacios_tipo_fk "
                + "FOREIGN KEY (tipo_espacio_id) REFERENCES tipos_espacio(id)");
    }

    private Map<String, Long> roleIds(Connection connection) throws Exception {
        List<RoleRow> roles = new ArrayList<>();
        try (Statement statement = connection.createStatement();
                ResultSet rows = statement.executeQuery("SELECT id, nombre FROM roles")) {
            while (rows.next()) {
                roles.add(new RoleRow(rows.getObject("id"), rows.getString("id"), rows.getString("nombre")));
            }
        }
        roles.sort(Comparator.comparingInt((RoleRow role) -> STANDARD_ROLE_IDS.containsKey(role.name()) ? 0 : 1)
                .thenComparing(RoleRow::name));
        Map<String, Long> ids = new HashMap<>();
        long nextId = 5;
        for (RoleRow role : roles) {
            Long id = STANDARD_ROLE_IDS.get(role.name());
            ids.put(role.key(), id != null ? id : nextId++);
        }
        return ids;
    }

    private Map<String, Long> typeIds(Connection connection) throws Exception {
        List<IdRow> types = new ArrayList<>();
        try (Statement statement = connection.createStatement();
                ResultSet rows = statement.executeQuery("SELECT id FROM tipos_espacio")) {
            while (rows.next()) {
                types.add(new IdRow(rows.getObject("id"), rows.getString("id")));
            }
        }
        types.sort(Comparator.comparingInt((IdRow type) -> STANDARD_TYPE_IDS.containsKey(type.key()) ? 0 : 1)
                .thenComparing(IdRow::key));
        Map<String, Long> ids = new HashMap<>();
        long nextId = 4;
        for (IdRow type : types) {
            Long id = STANDARD_TYPE_IDS.get(type.key());
            ids.put(type.key(), id != null ? id : nextId++);
        }
        return ids;
    }

    private List<Relation> readRelations(Connection connection, String table, String ownerColumn,
            String relationColumn, Map<String, Long> ids) throws Exception {
        List<Relation> relations = new ArrayList<>();
        try (Statement statement = connection.createStatement();
                ResultSet rows = statement.executeQuery("SELECT " + ownerColumn + ", " + relationColumn
                        + " FROM " + table)) {
            while (rows.next()) {
                Object ownerId = rows.getObject(ownerColumn);
                Object relatedId = rows.getObject(relationColumn);
                Long numericId = ids.get(rows.getString(relationColumn));
                if (numericId == null) {
                    throw new IllegalStateException("No numeric mapping found for " + table + "." + relationColumn);
                }
                relations.add(new Relation(ownerId, relatedId, numericId));
            }
        }
        return relations;
    }

    private void updateIds(Connection connection, String table, String newColumn, String oldColumn,
            Map<String, Long> ids) throws Exception {
        try (PreparedStatement update = connection.prepareStatement(
                "UPDATE " + table + " SET " + newColumn + " = ? WHERE " + oldColumn + " = ?")) {
            for (Map.Entry<String, Long> entry : ids.entrySet()) {
                Object oldId = findOldId(connection, table, oldColumn, entry.getKey());
                update.setLong(1, entry.getValue());
                update.setObject(2, oldId);
                update.addBatch();
            }
            update.executeBatch();
        }
    }

    private Object findOldId(Connection connection, String table, String idColumn, String idText) throws Exception {
        try (Statement statement = connection.createStatement();
                ResultSet rows = statement.executeQuery("SELECT " + idColumn + " FROM " + table)) {
            while (rows.next()) {
                Object id = rows.getObject(1);
                if (idText.equals(rows.getString(1))) {
                    return id;
                }
            }
        }
        throw new IllegalStateException("Catalog ID disappeared during migration: " + idText);
    }

    private void updateRelations(Connection connection, String table, String ownerColumn, String oldColumn,
            String newColumn, List<Relation> relations) throws Exception {
        try (PreparedStatement update = connection.prepareStatement("UPDATE " + table + " SET " + newColumn
                + " = ? WHERE " + ownerColumn + " = ? AND " + oldColumn + " = ?")) {
            for (Relation relation : relations) {
                update.setLong(1, relation.numericId());
                update.setObject(2, relation.ownerId());
                update.setObject(3, relation.relatedId());
                update.addBatch();
            }
            update.executeBatch();
        }
    }

    private void dropForeignKeyForColumn(Connection connection, String table, String column) throws Exception {
        DatabaseMetaData metadata = connection.getMetaData();
        List<String> names = new ArrayList<>();
        try (ResultSet keys = metadata.getImportedKeys(connection.getCatalog(), connection.getSchema(),
                tablePattern(metadata, table))) {
            while (keys.next()) {
                if (column.equalsIgnoreCase(keys.getString("FKCOLUMN_NAME"))) {
                    names.add(keys.getString("FK_NAME"));
                }
            }
        }
        for (String name : names) {
            execute(connection, "ALTER TABLE " + table + " DROP CONSTRAINT " + name);
        }
    }

    private void dropPrimaryKey(Connection connection, String table) throws Exception {
        DatabaseMetaData metadata = connection.getMetaData();
        List<String> names = new ArrayList<>();
        try (ResultSet keys = metadata.getPrimaryKeys(connection.getCatalog(), connection.getSchema(),
                tablePattern(metadata, table))) {
            while (keys.next()) {
                names.add(keys.getString("PK_NAME"));
            }
        }
        for (String name : names) {
            execute(connection, "ALTER TABLE " + table + " DROP CONSTRAINT " + name);
        }
    }

    private void replaceIdColumn(Connection connection, String table, String oldColumn, String newColumn,
            String primaryKeyName) throws Exception {
        execute(connection, "ALTER TABLE " + table + " DROP COLUMN " + oldColumn);
        execute(connection, "ALTER TABLE " + table + " RENAME COLUMN " + newColumn + " TO " + oldColumn);
        execute(connection, "ALTER TABLE " + table + " ADD CONSTRAINT " + primaryKeyName
                + " PRIMARY KEY (" + oldColumn + ")");
    }

    private void replaceReferenceColumn(Connection connection, String table, String oldColumn, String newColumn,
            String primaryKeyName) throws Exception {
        execute(connection, "ALTER TABLE " + table + " DROP COLUMN " + oldColumn);
        execute(connection, "ALTER TABLE " + table + " RENAME COLUMN " + newColumn + " TO " + oldColumn);
        if (primaryKeyName != null) {
            execute(connection, "ALTER TABLE " + table + " ADD CONSTRAINT " + primaryKeyName
                    + " PRIMARY KEY (usuario_id, rol_id)");
        }
    }

    private void execute(Connection connection, String sql) throws Exception {
        try (Statement statement = connection.createStatement()) {
            statement.execute(sql);
        }
    }

    private String tablePattern(DatabaseMetaData metadata, String table) throws Exception {
        if (metadata.storesUpperCaseIdentifiers()) {
            return table.toUpperCase(java.util.Locale.ROOT);
        }
        if (metadata.storesLowerCaseIdentifiers()) {
            return table.toLowerCase(java.util.Locale.ROOT);
        }
        return table;
    }

    private record RoleRow(Object id, String key, String name) {
    }

    private record IdRow(Object id, String key) {
    }

    private record Relation(Object ownerId, Object relatedId, Long numericId) {
    }
}
