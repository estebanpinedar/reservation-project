        updateMappedColumn(connection, "espacio_responsables", "usuario_id", "usuario_id_nuevo", users);
        updateMappedColumn(connection, "reservas", "usuario_creador_id", "usuario_creador_id_nuevo", users);
        updateMappedColumn(connection, "reservas", "espacio_id", "espacio_id_nuevo", spaces);
        updateMappedColumn(connection, "bloqueos", "espacio_id", "espacio_id_nuevo", spaces);
        updateMappedColumn(connection, "bloqueos", "usuario_creador_id", "usuario_creador_id_nuevo", users);
